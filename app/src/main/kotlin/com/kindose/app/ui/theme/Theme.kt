val KinDoseShapes = Shapes(
    extraSmall = RoundedCornerShape(10.dp),
    small = RoundedCornerShape(14.dp),
    medium = RoundedCornerShape(20.dp),
    large = RoundedCornerShape(28.dp),
    extraLarge = RoundedCornerShape(36.dp)
)

object KinDoseThemeTokens {
    val safetyColors: KinDoseSafetyColors
        @Composable
        @ReadOnlyComposable
        get() = LocalKinDoseSafetyColors.current
}

@Composable
fun KinDoseTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }

    val safetyColors = if (darkTheme) DarkSafetyColors else LightSafetyColors

    CompositionLocalProvider(LocalKinDoseSafetyColors provides safetyColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            shapes = KinDoseShapes,
            content = content
        )
    }
}
